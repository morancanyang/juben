def evidence(
    eid, title, kind, description, analysis, source, time, actors, hidden=False
):
    return dict(
        id=eid,
        title=title,
        type=kind,
        description=description,
        analysis=analysis,
        source=source,
        time=time,
        related_characters=actors,
        hidden=hidden,
    )


def statement(sid, text, keywords, condition=None):
    return dict(
        id=sid, text=text, keywords=keywords, condition=condition or {"op": "always"}
    )


def character(cid, name, role, bio, personality, color, statements):
    return dict(
        id=cid,
        name=name,
        role=role,
        bio=bio,
        personality=personality,
        color=color,
        statements=statements,
    )


def scene(sid, name, subtitle, description, objects, condition=None):
    return dict(
        id=sid,
        name=name,
        subtitle=subtitle,
        description=description,
        objects=[
            dict(
                id=f"o{i + 1}",
                name=o[0],
                description=o[1],
                evidence_id=o[2],
                condition=o[3] if len(o) > 3 else {"op": "always"},
            )
            for i, o in enumerate(objects)
        ],
        condition=condition or {"op": "always"},
    )


def question(qid, label, items):
    return dict(id=qid, label=label, options=[dict(id=i, label=t) for i, t in items])


